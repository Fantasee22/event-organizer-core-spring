import jakarta.annotation.PostConstruct
import jakarta.persistence.EntityManager
import org.springframework.beans.factory.config.ConfigurableListableBeanFactory
import org.springframework.context.ApplicationContext
import org.springframework.context.annotation.ClassPathScanningCandidateComponentProvider
import org.springframework.context.annotation.Configuration
import org.springframework.core.type.filter.AnnotationTypeFilter
import org.springframework.data.jpa.repository.support.JpaRepositoryFactory
import java.io.Serializable

@Configuration
class AutoRestControllerRegistrar(
    private val context: ApplicationContext,
    private val factory: ConfigurableListableBeanFactory,
    private val entityManager: EntityManager
) {

    @PostConstruct
    fun registerControllers() {
        // Create a scanner for @AutoGeneratedController annotations
        val scanner = ClassPathScanningCandidateComponentProvider(false)
        scanner.addIncludeFilter(AnnotationTypeFilter(AutoGeneratedController::class.java))

        val basePackage = "com.event_organizer_core_spring" // Adjust as needed
        val candidates = scanner.findCandidateComponents(basePackage)

        if (candidates.isEmpty()) {
            println("No @AutoGeneratedController-annotated classes found — skipping registration.")
            return
        }

        println("Found ${candidates.size} auto-generated controller classes")

        val entityManager = context.getBean(EntityManager::class.java)
        val repositoryFactory = JpaRepositoryFactory(entityManager)

        for (candidate in candidates) {
            val entityClass = Class.forName(candidate.beanClassName)

            // Try to infer ID type (default to Long if not found)
            val idField = entityClass.declaredFields.find { it.name == "id" }
            val idType = idField?.type ?: Long::class.java

            // Create repository
            @Suppress("UNCHECKED_CAST")
            val repository = repositoryFactory.getRepository(
                GenericRepository::class.java as Class<GenericRepository<Any, Serializable>>,
                entityClass
            ) as GenericRepository<Any, Serializable>

            // Create controller and register it as a Spring bean
            val controller = GenericController(repository)
            val beanName = entityClass.simpleName.replaceFirstChar { it.lowercaseChar() } + "Controller"

            factory.registerSingleton(beanName, controller)
            println("Registered GenericController for ${entityClass.simpleName} as $beanName")
        }
    }
}
