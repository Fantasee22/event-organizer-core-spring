import com.event_organizer_core_spring.core.annotation.AutoGeneratedController
import jakarta.annotation.PostConstruct
import org.springframework.beans.factory.config.ConfigurableListableBeanFactory
import org.springframework.context.ApplicationContext
import org.springframework.context.annotation.Configuration

@Configuration
class AutoRestControllerRegistrar(
    private val context: ApplicationContext,
    private val factory: ConfigurableListableBeanFactory
) {
    @PostConstruct
    fun registerControllers() {
        val entities = context.getBeansWithAnnotation(AutoGeneratedController::class.java)

        for ((beanName, entity) in entities) {
            val annotation = entity::class.java.getAnnotation(AutoGeneratedController::class.java)
            val repository = context.getBean("repositoryFor${entity::class.java.simpleName}") as GenericRepository<Any, Any>

            val controller = GenericController(repository)
            factory.registerSingleton("${beanName}Controller", controller)
        }
    }
}